-- ValoCase backend - "AA" as the stored value for "did not choose a country".
--
-- WHY A CODE RATHER THAN NULL
-- V80 left country_code nullable and said NULL means "never asked". That is still
-- true for every account created before the country screen existed. It cannot also
-- mean "was asked and skipped": one is a client that could not send a country, the
-- other is a player who saw the list and moved on. Collapsing them loses the only
-- signal that says whether the screen is doing its job, so the skip now has a value
-- of its own and NULL keeps its original meaning. No backfill runs; old rows stay
-- NULL forever, which is exactly what they mean.
--
-- WHY "AA"
-- ISO-3166-1 reserves AA for private use and will never assign it to a country, so
-- it cannot collide with a real one. It is also two uppercase ASCII letters, which
-- every VARCHAR(2) column, CHECK constraint, view and client parser already assumes
-- -- a marker such as "00" would have been the first value in the system to break
-- that shape.
--
-- The constraints are dropped and recreated rather than altered because Postgres
-- has no ADD-VALUE-TO-CHECK. The list below is the V80 list verbatim plus AA, and
-- AccountCountryIT reads it back out of pg_constraint and fails if it is not
-- exactly CountryCodes.all() -- the two copies stay honest by test, not by trust.

